/**
 * Generates src/core/data/types.ts from schema/charts.schema.json.
 *
 *   node scripts/gen-types.ts           writes the file (npm run types:gen)
 *   node scripts/gen-types.ts --check   exits 1 if the committed file differs (npm run types:check)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { compile, type JSONSchema } from 'json-schema-to-typescript';
import { format, resolveConfig } from 'prettier';

const schemaPath = fileURLToPath(new URL('../schema/charts.schema.json', import.meta.url));
const typesPath = fileURLToPath(new URL('../src/core/data/types.ts', import.meta.url));

const banner = `/*
 * Generated by \`npm run types:gen\` from schema/charts.schema.json. Do not edit it by hand:
 * change the schema and run \`npm run types:gen\`; \`npm run types:check\` fails while this file is stale.
 */`;

export async function generateTypes(): Promise<string> {
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8')) as JSONSchema;
  const source = await compile(schema, 'ChartData', {
    bannerComment: banner,
    unreachableDefinitions: true,
    additionalProperties: false,
    format: false,
  });
  const style = await resolveConfig(typesPath);
  return format(source, { ...style, filepath: typesPath });
}

async function main(): Promise<number> {
  const generated = await generateTypes();
  if (process.argv.includes('--check')) {
    let committed = '';
    try {
      committed = readFileSync(typesPath, 'utf8');
    } catch {
      // A missing file differs from the generated one.
    }
    if (committed !== generated) {
      console.error('types:check: src/core/data/types.ts is stale; run `npm run types:gen` and commit it.');
      return 1;
    }
    console.log('types:check: src/core/data/types.ts is up to date.');
    return 0;
  }
  writeFileSync(typesPath, generated);
  console.log('types:gen: wrote src/core/data/types.ts');
  return 0;
}

if (import.meta.main) {
  process.exitCode = await main();
}
